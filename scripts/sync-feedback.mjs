import { readFile, writeFile, mkdir, mkdtemp, rm, readdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { assertNoSymlinks, CHILDREN, ROOT } from './sync-contract.mjs';
const source='integration/compatibility/feedback/v1';
export async function syncFeedback({check=false}={}) {
 const temp=await mkdtemp(join(tmpdir(),'evopilot-feedback-'));
 try {
  const names=(await readdir(resolve(ROOT,source))).filter(n=>n.endsWith('.mts')&&!n.endsWith('.d.mts')).sort();
  const run=spawnSync(process.execPath,[resolve(ROOT,'node_modules/typescript/bin/tsc'),...names.map(n=>resolve(ROOT,source,n)),'--outDir',temp,'--rootDir',resolve(ROOT,'integration/compatibility'),'--target','ES2023','--module','NodeNext','--strict','--declaration','--noEmitOnError'],{cwd:ROOT,encoding:'utf8'});
  if(run.status!==0)throw Error(run.stdout+run.stderr);
  const files={};for(const name of names)for(const ext of ['.mjs','.d.mts'])files[name.replace(/\.mts$/,ext)]=await readFile(join(temp,'feedback/v1',name.replace(/\.mts$/,ext)));
  const sha=b=>createHash('sha256').update(b).digest('hex');
  const manifest={schema:'evopilot-feedback-distribution/v1',nativeContractUnchanged:true,files:Object.fromEntries(Object.entries(files).map(([n,b])=>[n,sha(b)])),sources:Object.fromEntries(await Promise.all(names.map(async n=>[n,sha(await readFile(resolve(ROOT,source,n)))])))};
  files['manifest.json']=Buffer.from(JSON.stringify(manifest,null,2)+'\n');
  for(const base of [source,...CHILDREN.map(c=>c+'/vendor/compatibility/feedback/v1')]) {
   for(const [name,bytes] of Object.entries(files)) {
    const p=resolve(ROOT,base,name);await assertNoSymlinks(p,true);
    if(check){if(!(await readFile(p)).equals(bytes))throw Error('Feedback generated byte mismatch: '+p);}
    else{await mkdir(resolve(ROOT,base),{recursive:true});await writeFile(p,bytes);}
   }
  }
 }finally{await rm(temp,{recursive:true,force:true});}
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)await syncFeedback({check:process.argv.includes('--check')});
